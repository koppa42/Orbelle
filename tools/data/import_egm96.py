"""Reproduce the compiled EGM96 20x20 table from the exact ICGEM source file.

Download (not performed by this script):
https://icgem.gfz.de/getmodel/gfc/971b0a3b49a497910aad23cd85e066d4cd9af0aeafe7ce6301a696bed8570be3/EGM96.gfc
Reference: Lemoine et al., NASA/TP-1998-206861. Fully normalized, tide-free.
"""
import argparse
import hashlib
from pathlib import Path

SOURCE_SHA256 = "5247a9e9c316dd2c8f8fd491d53be0e163cb5cb3676b021754240cc9e44cb43b"


def extract(source: Path) -> str:
    data = source.read_bytes()
    if hashlib.sha256(data).hexdigest() != SOURCE_SHA256:
        raise ValueError("EGM96 source SHA-256 differs from the reviewed model")
    coefficients = []
    for line in data.decode("ascii").splitlines():
        fields = line.split()
        if fields and fields[0] == "gfc" and 2 <= int(fields[1]) <= 20:
            n, m = int(fields[1]), int(fields[2])
            coefficients.append((n, m, fields[3], fields[4]))
    if [(n, m) for n, m, _, _ in coefficients] != [
        (n, m) for n in range(2, 21) for m in range(n + 1)
    ]:
        raise ValueError("EGM96 source has missing, repeated or unordered coefficients")
    return (
        "// Generated by tools/data/import_egm96.py; EGM96, fully normalized, tide-free.\n"
        f"// Source SHA-256: {SOURCE_SHA256}\n"
        "constexpr Coefficient egm96_coefficients[] = {\n"
        + "".join(f"    {{{n}, {m}, {c}, {s}}},\n" for n, m, c, s in coefficients)
        + "};\n"
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    args.output.write_text(extract(args.source), encoding="utf-8", newline="\n")
